jour = int(input("Veuillez entrer un chiffre entre 1 & 7 :"))

if jour == 1:
    print("Lundi")
elif jour == 2:
    print("Mardi")
elif jour == 3:
    print("Mercredi")
elif jour == 4:
    print("Jeudi")
elif jour == 5:
    print("Vendredi")
elif jour == 6:
    print("Samedi")
elif jour == 7:
    print("Dimanche")
else:
    print("Choix non prix en compte")